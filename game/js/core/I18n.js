  // ---- registry helpers ----
  function registry() {
    const map = {};
    LOCALES.forEach((l) => { map[l.code] = l; });
    OTHER_LOCALES.forEach((l) => { map[l.code] = l; });
    return map;
  }
  function localeInfo(code) {
    const all = registry();
    return all[code] || all.en;
  }
  function current() {
    const s = (MUNDA.state && MUNDA.state.settings) || {};
    return s.language || 'en';
  }
  function isOther(code) {
    return OTHER_LOCALES.some((l) => l.code === code);
  }

  // ---- translate ----
  function t(key, vars) {
    const code = current();
    let table = DICT[code];
    let val = table && table[key];
    if (val === undefined && OTHER_DICT[code]) val = OTHER_DICT[code][key];
    if (val === undefined) val = DICT.en[key];
    if (val === undefined) return key;
    if (vars) {
      return String(val).replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    }
    return val;
  }

  // ---- apply current language to all [data-i18n] elements ----
  function applyToDOM() {
    if (!U.$all) return;
    U.$all('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const attr = el.getAttribute('data-i18n-attr');
      if (attr) { el.setAttribute(attr, t(key)); }
      else el.textContent = t(key);
    });
  }

  function setLanguage(code) {
    if (!registry()[code]) return false;
    if (MUNDA.state && MUNDA.state.settings) {
      MUNDA.state.settings.language = code;
      if (MUNDA.storage) MUNDA.storage.saveSettings(MUNDA.state.settings);
    }
    applyToDOM();
    return true;
  }

